#!/usr/bin/env python3
"""Regenerate the generated block of graph-wasm.cabal.

The wasm build compiles some of the native library's modules (../src)
with its own cabal file. So that the file does not drift from the native
build, the block between the BEGIN and END lines is generated:

- default-extensions, ghc-options and cpp-options: the top-level lists of
  ../package.yaml;
- other-modules: the local modules that the modules in src import,
  transitively, found by reading their import lines.

Usage: sync-cabal.py [--check]. With --check, exits 1 if the file is out
of date instead of rewriting it.
"""

import re
import sys
from pathlib import Path

WASM = Path(__file__).resolve().parent
CLI = WASM.parent
CABAL = WASM / "graph-wasm.cabal"
SOURCE_DIRS = [WASM / "src", CLI / "src"]
BEGIN = "  -- BEGIN generated by sync-cabal.py\n"
END = "  -- END generated by sync-cabal.py\n"

IMPORT = re.compile(
    r"^import\s+(?:\{-#\s*SOURCE\s*#-\}\s+)?(?:qualified\s+)?"
    r'(?:"[^"]*"\s+)?([A-Z][\w.]*)',
    re.M,
)


def yaml_list(text, key):
    """The items of a top-level list in package.yaml (a plain `- item` list,
    as hpack files write them)."""
    match = re.search(rf"^{key}:\s*\n((?:(?:- .*|#.*|\s*)\n)*)", text, re.M)
    if not match:
        sys.exit(f"sync-cabal.py: no top-level {key} in package.yaml")
    return [
        line[2:].strip()
        for line in match.group(1).splitlines()
        if line.startswith("- ")
    ]


def module_file(module):
    for d in SOURCE_DIRS:
        path = d / (module.replace(".", "/") + ".hs")
        if path.exists():
            return path
    return None


def module_name(root, path):
    return ".".join(path.relative_to(root).with_suffix("").parts)


def closure(roots):
    """The local modules that the roots import, transitively, with them;
    an import that no source directory has is a package's."""
    seen = set()
    work = list(roots)
    while work:
        module = work.pop()
        if module in seen:
            continue
        path = module_file(module)
        if path is None:
            continue
        seen.add(module)
        work.extend(IMPORT.findall(path.read_text()))
    return seen


def field(name, items):
    return f"  {name}:\n" + "".join(f"    {i}\n" for i in items)


def generated():
    package_yaml = (CLI / "package.yaml").read_text()
    roots = [
        module_name(WASM / "src", p) for p in (WASM / "src").rglob("*.hs")
    ]
    modules = sorted(closure(roots) - {"Main"})
    lists = ["default-extensions", "ghc-options", "cpp-options"]
    return "".join(
        field(key, yaml_list(package_yaml, key)) for key in lists
    ) + field("other-modules", modules)


def main():
    check = sys.argv[1:] == ["--check"]
    text = CABAL.read_text()
    try:
        before, rest = text.split(BEGIN, 1)
        _, after = rest.split(END, 1)
    except ValueError:
        sys.exit(f"sync-cabal.py: no BEGIN/END lines in {CABAL}")
    new = before + BEGIN + generated() + END + after
    if new == text:
        return
    if check:
        sys.exit(f"{CABAL} is out of date: run {Path(__file__).name}")
    CABAL.write_text(new)
    print(f"sync-cabal.py: updated {CABAL.relative_to(CLI.parent)}")


if __name__ == "__main__":
    main()
