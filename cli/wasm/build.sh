#!/usr/bin/env bash
# Builds the WebAssembly reactor (path parsing, syntax feedback and
# completion without a graph) into dist/web/ and tests it under node.
#
# Needs ghc-wasm-meta's GHC 9.10 flavour (FLAVOUR=9.10 setup.sh), installed
# in $GHC_WASM_DIR (default ~/.ghc-wasm), python3 and curl. Everything else
# (PCRE, Hackage packages) it downloads and builds; the first build takes
# about 4 minutes.
#
# Usage: build.sh [--freeze] [--no-test]
#   --freeze   first regenerate cabal.project.freeze from the Stackage
#              snapshot that ../stack.yaml uses (after changing it)
#   --no-test  skip the node tests
set -euo pipefail

freeze=false
run_tests=true
for arg in "$@"; do
  case "$arg" in
    --freeze) freeze=true ;;
    --no-test) run_tests=false ;;
    *) echo "usage: $0 [--freeze] [--no-test]" >&2; exit 2 ;;
  esac
done

wasm_dir=$(cd "$(dirname "$0")" && pwd)
cd "$wasm_dir"
dist=$wasm_dir/dist
mkdir -p "$dist"
start=$SECONDS

ghc_version=9.10.3
pcre_version=8.45
pcre_sha256=4dae6fdcd2bb0bb6c37b5f97c33c2be954da743985369cddac3546e3218bffb8
pcre_url=https://downloads.sourceforge.net/project/pcre/pcre/$pcre_version/pcre-$pcre_version.tar.bz2

step() { printf '\n== %s (%ds)\n' "$1" $((SECONDS - start)); }

# --- toolchain
if ! command -v wasm32-wasi-ghc >/dev/null; then
  ghc_wasm_env=${GHC_WASM_DIR:-$HOME/.ghc-wasm}/env
  if [[ ! -f $ghc_wasm_env ]]; then
    echo "error: wasm32-wasi-ghc is not on PATH and $ghc_wasm_env is" \
      "missing; install ghc-wasm-meta's 9.10 flavour" >&2
    exit 1
  fi
  # shellcheck disable=SC1090
  source "$ghc_wasm_env"
fi
actual_version=$(wasm32-wasi-ghc --numeric-version)
if [[ $actual_version != "$ghc_version".* ]]; then
  echo "error: wasm32-wasi-ghc is $actual_version; the native build uses" \
    "GHC $ghc_version (stack.yaml), so the wasm build must too" >&2
  exit 1
fi

# --- PCRE for wasm32-wasi: pcre-light links it. GHC also loads it while
# compiling the [re|...|] splices, which needs libpcre.so; without it GHC
# hangs instead of failing.
pcre=$dist/pcre
if [[ ! -f $pcre/prefix/lib/libpcre.so ]]; then
  step "PCRE $pcre_version"
  rm -rf "$pcre"
  mkdir -p "$pcre/build"
  tarball=$pcre/pcre-$pcre_version.tar.bz2
  curl -fsSL -o "$tarball" "$pcre_url"
  echo "$pcre_sha256  $tarball" | shasum -a 256 -c -
  tar -xjf "$tarball" -C "$pcre"
  (
    cd "$pcre/build"
    "$pcre/pcre-$pcre_version/configure" --host=wasm32-wasi \
      --prefix="$pcre/prefix" --disable-shared --enable-static \
      --disable-cpp --enable-utf --enable-unicode-properties \
      CC=wasm32-wasi-clang CFLAGS="-O2 -mcpu=lime1 -fPIC" >configure.log
    # only the library: the test programs need what WASI lacks
    make -j"$(getconf _NPROCESSORS_ONLN)" libpcre.la >make.log
    make install-libLTLIBRARIES install-includeHEADERS \
      install-nodist_includeHEADERS >>make.log
  )
  wasm32-wasi-clang -shared -fPIC -Wl,--experimental-pic \
    -o "$pcre/prefix/lib/libpcre.so" \
    -Wl,--whole-archive "$pcre/prefix/lib/libpcre.a" -Wl,--no-whole-archive
fi
cat >"$dist/pcre.project" <<EOF
-- Generated by build.sh.
package pcre-light
  extra-include-dirs: $pcre/prefix/include
  extra-lib-dirs: $pcre/prefix/lib
EOF

# --- the cabal file's generated block
step "sync-cabal.py"
python3 sync-cabal.py

# --- versions: Stackage's, for stack.yaml's resolver
resolver=$(sed -n 's/^resolver: *\([^ #]*\).*/\1/p' ../stack.yaml)
# wasm32-wasi-cabal keeps its own CABAL_DIR, in the ghc-wasm-meta install
cabal_dir=$(cd "$(dirname "$(command -v wasm32-wasi-cabal)")/../.." \
  && pwd -P)/.cabal
if $freeze \
  || [[ ! -f $cabal_dir/packages/hackage.haskell.org/01-index.tar ]]; then
  step "wasm32-wasi-cabal update"
  wasm32-wasi-cabal update
fi
if $freeze; then
  step "freeze to $resolver"
  {
    echo "-- Generated by build.sh: Stackage's $resolver, then the Hackage"
    echo "-- extra-deps of stack.yaml."
    curl -fsSL "https://www.stackage.org/$resolver/cabal.config" \
      | grep -v '^with-compiler:'
    sed -n 's/^- \([A-Za-z][A-Za-z0-9-]*\)-\([0-9][0-9.]*\) *$/\1 \2/p' \
      ../stack.yaml \
      | while read -r name version; do
        echo "constraints: $name ==$version"
      done
  } >"$dist/stackage.config"
  rm -f freeze.project.freeze cabal.project.freeze
  wasm32-wasi-cabal freeze --project-file="$wasm_dir/freeze.project"
  {
    echo "-- Generated by build.sh --freeze from $resolver (stack.yaml)."
    cat freeze.project.freeze
  } >cabal.project.freeze
  rm freeze.project.freeze
fi
if ! grep -q "^-- Generated by build.sh --freeze from $resolver " \
  cabal.project.freeze; then
  echo "error: cabal.project.freeze is not from $resolver, stack.yaml's" \
    "resolver; run $0 --freeze" >&2
  exit 1
fi

# --- build
step "wasm32-wasi-cabal build"
wasm32-wasi-cabal build exe:graph
built=$(wasm32-wasi-cabal list-bin exe:graph)

step "post-link, wasm-opt"
web=$dist/web
rm -rf "$web"
mkdir -p "$web"
"$(wasm32-wasi-ghc --print-libdir)/post-link.mjs" \
  -i "$built" -o "$web/ghc_wasm_jsffi.js"
wasm-opt -Oz --strip-debug --strip-producers "$built" -o "$web/graph.wasm"
cp js/graph.mjs "$web/"

size() { wc -c <"$1" | tr -d ' '; }
echo "graph.wasm: $(size "$built") bytes linked," \
  "$(size "$web/graph.wasm") after wasm-opt," \
  "$(gzip -9c "$web/graph.wasm" | wc -c | tr -d ' ') gzipped"

if $run_tests; then
  step "node tests"
  GRAPH_WASM_DIR=$web node --test test/graph.test.mjs
fi
step "done: $web"
